import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { AddressInfo } from "node:net";
import { describe, expect, it } from "vitest";
import { epubFixture, epubEntry, EPUB_FIRST, EPUB_SECOND } from "../../../scripts/app-e2e/epub-fixture.ts";
import { epubBookCsp, epubFrameSandbox } from "../../../packages/contracts/src/epub.ts";
import { openEpubSession, epubText } from "./epub-ops.mjs";
import { Store } from "./store.ts";
import { EventBus } from "./bus.ts";
import { SessionManager } from "./sessions.ts";
import { createEditorsServer, EditorGrants, officeEditorKind } from "./editors.ts";

type Chapter = { ok: true; source: string; version: number; blocks: { id: string; kind: string; inner: { start: number; end: number } }[] };
describe("original EPUB editor", () => {
  it("retains original bytes and refuses damaged/DRM and fixed-layout/broken chapter edits", async () => {
    expect(officeEditorKind("epub")).toBe("epub");
    const bytes = await epubFixture(), before = Buffer.from(bytes), opened = await openEpubSession(bytes);
    expect(await epubText(bytes)).toContain("Second chapter text stays.");
    if (!opened.ok) throw new Error(opened.reason);
    expect((await opened.session.prepareSave()).result).toMatchObject({ ok: true, changed: false });
    expect(bytes).toEqual(before);
    expect(await openEpubSession(Buffer.from("not epub"))).toEqual({ ok: false, reason: "damaged" });
    expect(await openEpubSession(await epubFixture("locked", { drm: true }))).toEqual({ ok: false, reason: "drm" });
    const fixed = await openEpubSession(await epubFixture("fixed", { fixed: true }));
    if (!fixed.ok) throw new Error(fixed.reason);
    const chapter = await fixed.session.readChapter(0) as Chapter;
    expect(await fixed.session.applyEdits(0, [{ op: "replace", blockId: chapter.blocks[0]!.id, text: "bad" }])).toMatchObject({ ok: false, error: "read-only" });
    const broken = await openEpubSession(await epubFixture("normal", { broken: true }));
    if (!broken.ok) throw new Error(broken.reason);
    expect(await broken.session.readChapter(1)).toMatchObject({ ok: true, broken: true, readOnly: "broken-chapter" });
  });

  it("scopes chapter edits/assets, saves ranges, preserves history and restores confirmed recovery copies", async () => {
    const dir = mkdtempSync(join(tmpdir(), "wb-epub-http-")), store = new Store(join(dir, "state.sqlite"));
    const manager = new SessionManager(store, new EventBus(), { hostId: "test", hostLabel: "test", managedWorksDir: join(dir, "works"), dataDir: dir });
    const work = manager.createWork({ title: "EPUB", cwd: join(dir, "project") }); mkdirSync(work.cwd, { recursive: true });
    const original = await epubFixture(), file = join(work.cwd, "전자책.epub"); writeFileSync(file, original);
    const artifact = manager.openFile(work.id, file), documents = manager.documents;
    const writer = documents.registry.open(artifact.id, { viewId: "writer", windowId: "writer", claim: true });
    const reader = documents.registry.open(artifact.id, { viewId: "reader", windowId: "reader", claim: true });
    const grants = new EditorGrants(); let token = grants.issue(artifact.id, { viewId: "writer", writeToken: writer.writeToken });
    const readToken = grants.issue(artifact.id, { viewId: "reader", writeToken: reader.writeToken });
    const server = createEditorsServer(documents, grants, null); await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve));
    const origin = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
    const call = (op: string, args: unknown = {}, session = "", grant = token) => fetch(`${origin}/api/artifacts/${artifact.id}/epub/${op}?session=${session}`, { method: "POST", headers: { authorization: `Bearer ${grant}` }, body: JSON.stringify(args) });
    const open = (revision: number, bytes?: Uint8Array, grant = token) => fetch(`${origin}/api/artifacts/${artifact.id}/epub/open?revision=${revision}${bytes ? "&restore=1" : ""}`, { method: "POST", headers: { authorization: `Bearer ${grant}` }, body: bytes ? bytes.slice().buffer : undefined });
    try {
      expect((await open(1, undefined, "forged")).status).toBe(401);
      const initial = await (await open(1)).json(), sid = initial.sessionId as string;
      expect(initial).toMatchObject({ status: "ok", readOnly: null, workbenchReadOnly: false });
      expect((await documents.text(artifact.id)).editable).toBe(false);
      await expect(documents.saveText(artifact.id, 1, "ZIP must not become text", { viewId: "writer", writeToken: writer.writeToken })).rejects.toMatchObject({ code: "binary_document" });
      expect((await call("chapter", { spineIndex: 0 }, sid, readToken)).status).toBe(404);
      const ro = await (await open(1, undefined, readToken)).json();
      expect((await call("apply", {}, ro.sessionId, readToken)).status).toBe(423);
      expect((await call("save", { expectedRevision: 1 }, ro.sessionId, readToken)).status).toBe(423);
      const image = await fetch(origin + initial.assetBase + "OEBPS/images/picture.png");
      expect(image.status).toBe(200); expect(image.headers.get("content-type")).toBe("image/png");
      expect(image.headers.get("content-security-policy")).toContain(origin + initial.assetBase);
      expect(image.headers.get("content-security-policy")).toContain("script-src 'none'");
      expect((await fetch(origin + initial.assetBase + "OEBPS/evil.js")).status).toBe(403);
      expect((await fetch(origin + initial.assetBase + "%2E%2E/%2E%2E/etc/passwd")).status).toBe(404);
      expect((await fetch(origin + initial.assetBase + "OEBPS/images/picture.png", { method: "POST" })).status).toBe(405);
      expect((await call("save", { expectedRevision: 1 }, sid)).status).toBe(200); expect(readFileSync(file)).toEqual(original);
      let chapter = await (await call("chapter", { spineIndex: 0 }, sid)).json() as Chapter;
      const block = chapter.blocks.find((b) => b.kind === "p")!;
      const edit = await (await call("apply", { spineIndex: 0, edits: [{ op: "replace", blockId: block.id, text: "Changed paragraph." }] }, sid)).json();
      expect(edit).toMatchObject({ ok: true, dirty: true });
      expect((await (await call("replace", { spineIndex: 0, version: chapter.version, replacements: [] }, sid)).json()).error).toBe("stale");
      expect((await call("close", {}, sid)).status).toBe(409);
      const undone = await (await call("replace", { spineIndex: 0, version: edit.version, replacements: edit.inverse }, sid)).json();
      expect(undone).toMatchObject({ ok: true, dirty: false });
      expect((await call("save", { expectedRevision: 1 }, sid)).status).toBe(200); expect(readFileSync(file)).toEqual(original);
      await call("lock", { locked: true }, sid);
      expect((await (await call("apply", { spineIndex: 0, edits: [{ op: "replace", blockId: block.id, text: "locked" }] }, sid)).json()).error).toBe("locked");
      await call("lock", { locked: false }, sid);
      await call("apply", { spineIndex: 0, edits: [{ op: "replace", blockId: block.id, text: "Changed paragraph." }] }, sid);
      expect((await (await call("save", { expectedRevision: 1 }, sid)).json()).revision).toBe(2);
      const saved = readFileSync(file);
      expect((await epubEntry(saved, "OEBPS/text/one.xhtml"))!.toString()).toBe(EPUB_FIRST.replace("First paragraph.", "Changed paragraph."));
      expect((await epubEntry(saved, "OEBPS/text/two.xhtml"))!.toString()).toBe(EPUB_SECOND);
      expect(await epubEntry(saved, "future/unknown.bin")).toEqual(await epubEntry(original, "future/unknown.bin"));
      expect(readFileSync(documents.revisionPath(artifact.id, 1))).toEqual(original);
      // A refreshed grant retains this exact view's book; another view cannot borrow it.
      token = grants.issue(artifact.id, { viewId: "writer", writeToken: writer.writeToken });
      expect((await call("chapter", { spineIndex: 0 }, sid)).status).toBe(200);
      await call("prefs", { patch: { fontScale: 1.5, dark: true } }, sid);
      await call("position", { position: { spineIndex: 1, blockId: null } }, sid);
      expect(await (await call("reading", {}, sid)).json()).toMatchObject({ position: { spineIndex: 1 }, viewPrefs: { fontScale: 1.5, dark: true } });
      expect(readFileSync(file)).toEqual(saved);
      // Capture pending input after losing the write lease, but never overwrite the disk.
      documents.registry.close("writer", "writer");
      chapter = await (await call("chapter", { spineIndex: 0 }, sid)).json() as Chapter;
      const p = chapter.blocks.find((b) => b.kind === "p")!;
      expect((await (await call("apply", { spineIndex: 0, edits: [{ op: "replace", blockId: p.id, text: "Recovered paragraph." }] }, sid)).json()).ok).toBe(true);
      expect((await call("save", { expectedRevision: 2 }, sid)).status).toBe(423);
      const checkpoint = await call("checkpoint", {}, sid), bytes = Buffer.from(await checkpoint.arrayBuffer());
      expect((await epubEntry(bytes, "OEBPS/text/one.xhtml"))!.toString()).toContain("Recovered paragraph.");
      expect(readFileSync(file)).toEqual(saved);
      expect((await call("close", {}, sid)).status).toBe(409);
      await call("checkpoint-confirm", { checkpoint: checkpoint.headers.get("x-epub-checkpoint") }, sid);
      expect((await call("close", {}, sid)).status).toBe(200);
      expect((await fetch(origin + initial.assetBase + "OEBPS/images/picture.png")).status).toBe(404);
      const nextWriter = documents.registry.open(artifact.id, { viewId: "writer", windowId: "writer", claim: true });
      token = grants.issue(artifact.id, { viewId: "writer", writeToken: nextWriter.writeToken });
      const external = await epubFixture("External paragraph."); writeFileSync(file, external); documents.adoptDisk(artifact.id);
      const recovered = await (await open(2, bytes)).json();
      expect((await call("save", { expectedRevision: 2 }, recovered.sessionId)).status).toBe(409);
      expect(readFileSync(file)).toEqual(external);
      expect((await (await call("save", { expectedRevision: 3, rebase: true }, recovered.sessionId)).json()).revision).toBe(4);
      expect(readFileSync(file)).toEqual(bytes);
      expect(readFileSync(documents.revisionPath(artifact.id, 3))).toEqual(external);
      expect(await (await open(4, Buffer.from("invalid recovery"))).json()).toMatchObject({ status: "refused", reason: "damaged" });
      expect(readFileSync(file)).toEqual(bytes);
    } finally { await new Promise<void>((resolve) => server.close(() => resolve())); store.close(); rmSync(dir, { recursive: true, force: true }); }
  });

  it("limits chapter policies to a single loopback book, without a broad same-origin escape", () => {
    const base = `http://127.0.0.1:1234/epub-assets/${"a".repeat(48)}/`;
    expect(epubBookCsp(base + "OEBPS/text/one.xhtml")).toContain(`base-uri ${base}`);
    expect(epubBookCsp(base)).not.toContain("'self'");
    expect(() => epubBookCsp("https://example.com/epub-assets/" + "a".repeat(48) + "/")).toThrow();
    expect(() => epubBookCsp("http://127.0.0.1:1234/api/artifacts/")).toThrow();
    expect(epubFrameSandbox("AppleWebKit/605.1.15 Version/60.5 Safari/605.1.15")).toBe("allow-same-origin allow-scripts");
    expect(epubFrameSandbox("AppleWebKit/537.36 Chrome/120 Safari/537.36 Edg/120")).toBe("allow-same-origin");
    expect(epubFrameSandbox("Gecko/20100101 Firefox/120")).toBe("allow-same-origin");
  });
});
