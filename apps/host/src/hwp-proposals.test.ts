import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { beforeAll, expect, it } from "vitest";
import init, { HwpDocument } from "../../../vendor/ieumoffice/vendor/rhwp-core/rhwp.js";
import { hwpWasmPath } from "./hwp-resource.ts";
import { editHwp } from "./hwp-ops.mjs";
import { EventBus } from "./bus.ts";
import { SessionManager } from "./sessions.ts";
import { Store } from "./store.ts";

beforeAll(async () => { await init({ module_or_path: readFileSync(hwpWasmPath()) }); });
for (const format of ["hwp", "hwpx"] as const) it(`pins a binary ${format} proposal and checks it again at user apply`, async () => {
  const dir = mkdtempSync(join(tmpdir(), "wb-hwp-proposal-"));
  const manager = new SessionManager(new Store(join(dir, "state.sqlite")), new EventBus(), { hostId: "test", hostLabel: "test", managedWorksDir: join(dir, "works"), dataDir: dir, kordoc: null });
  const work = manager.createWork({ title: "한글", cwd: join(dir, "project") }); mkdirSync(work.cwd, { recursive: true });
  const engine = HwpDocument.createEmpty(); engine.createBlankDocument(); engine.insertText(0, 0, 0, "한글 본문 원본 유지");
  engine.insertMemo(0, 0, 0, 2, JSON.stringify({ author: "검토자", text: "메모 유지" }));
  const original = Buffer.from(format === "hwp" ? engine.exportHwp() : engine.exportHwpx()); engine.free();
  const path = join(work.cwd, `document.${format}`); writeFileSync(path, original);
  const artifact = manager.openFile(work.id, path), session = manager.createSession(work.id, { provider: "codex" });
  const ref = { artifactId: artifact.id, mode: "edit" as const, revision: 1, selection: null };
  const prepared = await manager.documents.prepare(ref, session.id, "native-hwp", work.cwd), proposal = prepared.proposal!;
  expect(proposal.workingPath.endsWith(`.${format}`)).toBe(true);
  expect(readFileSync(proposal.workingPath)).toEqual(original); expect(readFileSync(prepared.pinned)).toEqual(original);
  expect(readFileSync(prepared.pinnedView!, "utf8")).toContain("한글 본문");
  expect(manager.documents.promptFor(ref, prepared.pinned, proposal, work.cwd, prepared.pinnedView)).toContain("workbench-hwp");
  const edited = await editHwp(original, format, [{ op: "replace_text", find: "원본 유지", replace: "안전하게 수정" }]);
  writeFileSync(proposal.workingPath, edited.bytes);
  expect(manager.documents.finishProposal(proposal.id).status).toBe("pending");
  expect(readFileSync(path)).toEqual(original);
  expect((await manager.documents.proposalTexts(proposal.id)).proposed).toContain("안전하게 수정");
  // A corrupted or switched working copy must not be applied just because an earlier check passed.
  writeFileSync(proposal.workingPath, "bad container");
  await expect(manager.documents.applyProposal(proposal.id)).rejects.toMatchObject({ status: 422 });
  expect(readFileSync(path)).toEqual(original);
  writeFileSync(proposal.workingPath, edited.bytes);
  const writer = manager.documents.registry.open(artifact.id, { viewId: "one", windowId: "one", claim: true });
  await expect(manager.documents.applyProposal(proposal.id)).rejects.toMatchObject({ status: 423 });
  const result = await manager.documents.applyProposal(proposal.id, { viewId: "one", writeToken: writer.writeToken });
  expect(result.artifact.revision).toBe(2);
  expect((await manager.documents.text(artifact.id)).text).toContain("안전하게 수정");
  expect(readFileSync(manager.documents.revisionPath(artifact.id, 1))).toEqual(original);
  const stale = (await manager.documents.prepare({ ...ref, revision: 2 }, session.id, "stale-hwp", work.cwd)).proposal!;
  const next = await editHwp(readFileSync(path), format, [{ op: "replace_text", find: "안전하게 수정", replace: "뒤늦은 수정" }]);
  writeFileSync(stale.workingPath, next.bytes); manager.documents.finishProposal(stale.id);
  writeFileSync(path, original); manager.documents.adoptDisk(artifact.id);
  await expect(manager.documents.applyProposal(stale.id, { viewId: "one", writeToken: writer.writeToken })).rejects.toMatchObject({ code: "stale_proposal" });
  expect(readFileSync(path)).toEqual(original);
});
